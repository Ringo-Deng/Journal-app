import { readFile, mkdir, copyFile, writeFile, stat } from 'node:fs/promises';
import { join, resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { createReadStream } from 'node:fs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const appFile = `shiguang-journal-v${version}-mac-arm64.zip`;
const windowsFile = `shiguang-journal-v${version}-windows-x64.zip`;
const windowsSource = join(root, 'build/windows-delivery', windowsFile);
const materialSource = process.argv[2];
if (!materialSource) throw Error('请显式指定已经核对过的合并后的 .shiguang-materials 路径。');
const materialFile = 'shiguang-materials.shiguang-materials';
const appSource = join(root, 'build/desktop', appFile);
const appInfo = await stat(appSource), windowsInfo = await stat(windowsSource), materialInfo = await stat(materialSource);
if (!appInfo.isFile() || !windowsInfo.isFile() || !materialInfo.isFile() || !materialSource.endsWith('.shiguang-materials')) throw Error('应用必须为文件，素材必须为 .shiguang-materials 文件。');
const output = join(root, 'build', `shiguang-intro-v${version}`);
await mkdir(join(output, 'downloads'), { recursive: true });
await mkdir(join(output, 'assets'), { recursive: true });
await copyFile(appSource, join(output, 'downloads', appFile));
await copyFile(windowsSource, join(output, 'downloads', windowsFile));
await copyFile(materialSource, join(output, 'downloads', materialFile));
for (const name of ['green-collage-example.png', 'material-library-preview.png'])
  await copyFile(join(root, 'website/assets', name), join(output, 'assets', name));
const size = bytes => `${Math.round(bytes / 1024 / 1024)} MB`;
const downloadBase = process.argv[3] || 'downloads';
if (downloadBase !== 'downloads' && !/^https:\/\/github\.com\/Ringo-Deng\/Journal-app\/releases\/download\/v[0-9.]+$/.test(downloadBase)) throw Error('下载地址必须使用本仓库的版本 Release。');
const values = { VERSION: version, APP_FILE: appFile, WINDOWS_FILE: windowsFile, WINDOWS_SIZE: size(windowsInfo.size), MATERIAL_FILE: materialFile, APP_SIZE: size(appInfo.size), MATERIAL_SIZE: size(materialInfo.size) };
let html = await readFile(join(root, 'website/index.template.html'), 'utf8');
for (const [key, value] of Object.entries(values)) html = html.replaceAll(`{{${key}}}`, value);
html = html.replaceAll('href="downloads/', `href="${downloadBase}/`);
if (/\{\{[A-Z_]+\}\}/.test(html)) throw Error('页面存在未替换的字段。');
await writeFile(join(output, 'index.html'), html);
const hashes = [];
for (const name of [appFile, windowsFile, materialFile]) {
  const hash = createHash('sha256');
  for await (const part of createReadStream(join(output, 'downloads', name))) hash.update(part);
  hashes.push(`${hash.digest('hex')}  downloads/${name}`);
}
await writeFile(join(output, 'SHA256SUMS.txt'), hashes.join('\n') + '\n');
await writeFile(join(output, '使用说明.txt'), '解压后打开 index.html，即可查看功能介绍并下载 Mac、Windows 应用及素材合集。\n请保留 assets 和 downloads 文件夹；分享时发送整个文件夹或完整 ZIP。\n此页面尚未发布到公网。部署时需保持相对路径，下载文件需要支持大文件的存储空间。\n');
console.log(`介绍页：${join(output, 'index.html')}\n分享目录：${basename(output)}`);
